export type IconName = keyof typeof BITMAPS | ConditionGlyph;

const PATHS: Record<string, string> = {};
function pathFor(name: keyof typeof BITMAPS): string {
  if (PATHS[name]) return PATHS[name];
  let d = "";
  BITMAPS[name].forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") { x++; continue; }
      let len = 0;
      while (row[x + len] === "#") len++;
      d += `M${x} ${y}h${len}v1h-${len}z`;
      x += len;
    }
  });
  return (PATHS[name] = d);
}

export function PixelIcon({ name, size = 16, class: cls }: { name: IconName; size?: number; class?: string }) {
  const key = name as keyof typeof BITMAPS; // todo ConditionGlyph existe em BITMAPS
  return (
    <svg class={`px-icon${cls ? ` ${cls}` : ""}`} width={size} height={size} viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">
      <path d={pathFor(key)} fill="currentColor" />
    </svg>
  );
}
